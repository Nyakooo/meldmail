#!/usr/bin/env python3
"""Regenerate shipped notices from installed Go and Vue runtime dependencies."""
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def main():
    packages = subprocess.check_output(
        ['go', 'list', '-deps', '-test', '-f',
         '{{if .Module}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}{{end}}', './...'],
        cwd=ROOT, text=True)
    dependencies = {}
    for line in packages.splitlines():
        if not line:
            continue
        name, version, directory = line.split('|')
        if version:
            dependencies[(name, version)] = Path(directory)
    for name in ('vue', '@vue/shared', '@vue/reactivity', '@vue/runtime-core', '@vue/runtime-dom'):
        directory = ROOT / 'web' / 'node_modules' / name
        package = json.loads((directory / 'package.json').read_text())
        dependencies[(name, package['version'])] = directory
    goroot = Path(subprocess.check_output(['go', 'env', 'GOROOT'], text=True).strip())
    dependencies[('Go runtime and standard library', 'see go.mod / build toolchain')] = goroot
    text = ['# Third-party notices\n',
            'Generated by `scripts/update-notices.py` from Go production/test imports and '
            'Vue runtime packages. The official MCP SDK and its exclusive dependencies '
            'are used only in tests. These licenses apply to their respective upstream '
            'components; MeldMail source is Apache-2.0. Alpine packages retain their '
            'upstream licenses in the base image.\n']
    for (name, version), directory in sorted(dependencies.items()):
        licenses = sorted({p for pattern in ('LICENSE*', 'LICENCE*', 'COPYING*', 'NOTICE*')
                           for p in directory.glob(pattern) if p.is_file()})
        if not licenses:
            raise RuntimeError(f'missing license for {name} {version}')
        text.append(f'\n## {name} {version}\n')
        for license_file in licenses:
            text.append(f'\n### {license_file.name}\n\n```text\n'
                        + license_file.read_text().rstrip() + '\n```\n')
    (ROOT / 'THIRD_PARTY_NOTICES.md').write_text('\n'.join(text))
    print(f'Updated notices for {len(dependencies)} dependencies/toolchain entries')


if __name__ == '__main__':
    main()
